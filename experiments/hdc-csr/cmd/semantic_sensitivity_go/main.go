package main

import (
	"crypto/sha256"
	"encoding/binary"
	"encoding/hex"
	"encoding/json"
	"flag"
	"fmt"
	"math"
	"os"
	"path/filepath"

	hdccsr "github.com/kbelludoo/mbvm-db/experiments/hdc-csr"
)

type caseSet struct {
	Schema string `json:"schema"`
	Cases []struct {
		ID string `json:"id"`
		Original string `json:"original"`
		Equivalent string `json:"equivalent"`
		Changed string `json:"changed"`
	} `json:"cases"`
}
type featureMetadata struct {
	Schema string `json:"schema"`
	Rows int `json:"rows"`
	Dimensions int `json:"dimensions"`
	OrderedFields []string `json:"ordered_fields"`
	FixtureSHA256 string `json:"fixture_sha256"`
	FeaturesSHA256 string `json:"features_sha256"`
	SourceDigest string `json:"source_digest"`
	EncoderModel string `json:"encoder_model"`
}
type row struct {
	ID string `json:"id"`
	EquivalentBits int `json:"equivalent_bits"`
	ChangedBits int `json:"changed_bits"`
	SeparationBits int `json:"functional_separation_bits"`
	CorrectOrder bool `json:"correct_order"`
}
type report struct {
	Schema string `json:"schema"`
	ProjectionSourceDigest string `json:"projection_source_digest"`
	EncoderModel string `json:"encoder_model"`
	FixtureSHA256 string `json:"fixture_sha256"`
	ProjectionSHA256 string `json:"projection_sha256"`
	CorrectPairOrder int `json:"correct_pair_order"`
	TotalPairs int `json:"total_pairs"`
	PairOrderAccuracy float64 `json:"pair_order_accuracy"`
	Results []row `json:"results"`
	Limitations []string `json:"limitations"`
}
func digest(data []byte)string{sum:=sha256.Sum256(data);return hex.EncodeToString(sum[:])}

func run(casesPath,featuresPath,metaPath,projectionPath,outPath string)error{
	casesBytes,err:=os.ReadFile(casesPath)
	if err!=nil{return err}
	var cases caseSet
	if err=json.Unmarshal(casesBytes,&cases);err!=nil{return err}
	if cases.Schema!="mbvm-semantic-sensitivity-v1"||len(cases.Cases)!=5{
		return fmt.Errorf("expected five labeled Go behavior cases")
	}
	metaBytes,err:=os.ReadFile(metaPath)
	if err!=nil{return err}
	var meta featureMetadata
	if err=json.Unmarshal(metaBytes,&meta);err!=nil{return err}
	if meta.Schema!="mbvm-semantic-features-v1"||meta.Rows!=len(cases.Cases)*3||meta.Dimensions!=384||
		len(meta.OrderedFields)!=3||meta.OrderedFields[0]!="original"||
		meta.OrderedFields[1]!="equivalent"||meta.OrderedFields[2]!="changed" {
		return fmt.Errorf("incompatible ordered MiniLM feature manifest")
	}
	if meta.FixtureSHA256!=digest(casesBytes){
		return fmt.Errorf("Go code cases changed since MiniLM feature export")
	}
	features,err:=os.ReadFile(featuresPath)
	if err!=nil{return err}
	if len(features)!=meta.Rows*384*4||meta.FeaturesSHA256!=digest(features){
		return fmt.Errorf("MiniLM feature size or SHA256 mismatch")
	}
	proj,err:=hdccsr.LoadNativeProjection8K(projectionPath)
	if err!=nil{return err}
	if meta.SourceDigest!=proj.SourceDigest{
		return fmt.Errorf("source digest mismatch: projected weights and features come from different training sources")
	}
	projected:=make([]hdccsr.Hypervector,meta.Rows)
	for rowID:=0;rowID<meta.Rows;rowID++ {
		x:=make([]float32,384)
		start:=rowID*384*4
		for j:=0;j<384;j++{
			v:=math.Float32frombits(binary.LittleEndian.Uint32(features[start+4*j:]))
			x[j]=v
		}
		projected[rowID],err=proj.ProjectNormalizedMiniLM384(x)
		if err!=nil{return fmt.Errorf("row %d: %w",rowID,err)}
	}
	projectionBytes,err:=os.ReadFile(projectionPath)
	if err!=nil{return err}
	result:=report{
		Schema:"mbvm-go-semantic-sensitivity-v1",
		ProjectionSourceDigest:proj.SourceDigest,
		EncoderModel:meta.EncoderModel,
		FixtureSHA256:meta.FixtureSHA256,
		ProjectionSHA256:digest(projectionBytes),
		TotalPairs:len(cases.Cases),
		Results:make([]row,0,len(cases.Cases)),
		Limitations:[]string{
			"384D text embeddings were generated by a separate frozen MiniLM encoder, not by the Go binary projection.",
			"Pair labels are verified over 225 bounded Go integer inputs, not all possible programs.",
			"The original Kaggle projection was trained on teacher embedding similarity, not this pair-order objective.",
			"5 examples are insufficient to claim broad semantic code understanding or calibrate probabilities.",
			"Go's float32 sum may differ from PyTorch near decision margins; compare bitwise parity separately.",
		},
	}
	for i,c:=range cases.Cases {
		k:=3*i
		dEq:=hdccsr.HammingDistance(projected[k],projected[k+1])
		dChange:=hdccsr.HammingDistance(projected[k],projected[k+2])
		r:=row{ID:c.ID,EquivalentBits:dEq,ChangedBits:dChange,
			SeparationBits:dChange-dEq,CorrectOrder:dEq<dChange}
		if r.CorrectOrder{result.CorrectPairOrder++}
		result.Results=append(result.Results,r)
		fmt.Printf("%s: equivalent=%d changed=%d margin=%+d bits\n",r.ID,dEq,dChange,r.SeparationBits)
	}
	result.PairOrderAccuracy=float64(result.CorrectPairOrder)/float64(result.TotalPairs)
	blob,err:=json.MarshalIndent(result,"","  ")
	if err!=nil{return err}
	if err=os.MkdirAll(filepath.Dir(outPath),0755);err!=nil{return err}
	if err=os.WriteFile(outPath,append(blob,'\n'),0644);err!=nil{return err}
	fmt.Printf("Correct ordering: %d/%d = %.1f%%\n",result.CorrectPairOrder,result.TotalPairs,100*result.PairOrderAccuracy)
	return nil
}
func main(){
	casesPath:=flag.String("cases","experiments/hdc-csr/semantic_sensitivity_cases.json","five independent behavior-labeled Go cases")
	features:=flag.String("features","output/real/semantic_features.f32le","offline MiniLM384 embedding matrix")
	meta:=flag.String("metadata","output/real/semantic_features.json","embedding feature metadata")
	projection:=flag.String("projection","output/real/projection_go_v1.bin","verified float32 384x8192 projection")
	out:=flag.String("out","output/real/semantic_sensitivity_go.json","Go evaluation report")
	flag.Parse()
	if err:=run(*casesPath,*features,*meta,*projection,*out);err!=nil{
		fmt.Fprintln(os.Stderr,"semantic sensitivity evaluation:",err)
		os.Exit(1)
	}
}
